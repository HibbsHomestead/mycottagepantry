import { writeFileSync } from 'node:fs'
import { join } from 'node:path'

const siteId = '299e7942-6246-467a-bef5-fa3f6817b210'

/** Only public deployment identifiers are allowed into the Functions bundle. */
export function publicDeploymentMetadata(env: NodeJS.ProcessEnv) {
  if (
    env.SITE_ID !== siteId ||
    !/^[a-f0-9]{24}$/.test(env.DEPLOY_ID || '') ||
    !['production', 'deploy-preview', 'branch-deploy'].includes(
      env.CONTEXT || '',
    )
  )
    return null
  const review =
    /^https:\/\/((?:deploy-preview-[0-9]+|agent-[a-f0-9]{24}))--mycottagepantry\.netlify\.app$/.exec(
      env.DEPLOY_PRIME_URL || '',
    )
  return {
    siteId,
    deployId: env.DEPLOY_ID!,
    context: env.CONTEXT!,
    previewOrigin:
      env.CONTEXT === 'deploy-preview' && review
        ? `https://${review[1]}--mycottagepantry.netlify.app`
        : '',
  }
}

export function writeDeploymentMetadata(root: string, env: NodeJS.ProcessEnv) {
  const metadata = publicDeploymentMetadata(env)
  if (!metadata) return
  writeFileSync(
    join(root, 'netlify/lib/deployment-metadata.ts'),
    '// Public metadata generated by the managed build. No credentials.\n' +
      'export const deploymentMetadata = ' +
      JSON.stringify(metadata, null, 2) +
      '\n',
  )
}
