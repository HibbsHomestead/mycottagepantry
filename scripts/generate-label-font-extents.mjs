// Run after changing bundled label fonts. No application or database startup.
import fs from 'node:fs/promises'
import fontkit from '@pdf-lib/fontkit'
const extents = {}
for (const filename of (await fs.readdir('public/label-fonts')).sort()) {
  if (!filename.endsWith('.ttf')) continue
  const face = fontkit.create(await fs.readFile('public/label-fonts/' + filename))
  extents[filename.slice(0, -4)] = {
    ascent: Math.max(face.ascent, face.bbox.maxY) / face.unitsPerEm,
    descent: Math.max(-face.descent, -face.bbox.minY) / face.unitsPerEm,
  }
}
await fs.writeFile('src/lib/label-font-extents.ts',
  '// Generated by scripts/generate-label-font-extents.mjs from bundled font files.\n' +
  'export const labelFontExtents: Record<string, { ascent: number; descent: number }> = ' +
  JSON.stringify(extents) + '\n')
