export type LabelFont = Omit<(typeof bundledFonts)[number], 'styles'> & {
  styles: string[]
  source: 'bundled' | 'google' | 'custom'
  browserFormat?: string
  googleStyle?: string
}
export const bundledLabelFonts: LabelFont[] = bundledFonts.map((f) => ({
  ...f,
  source: 'bundled',
}))
export function googleFontKey(name: string) {
  return 'google-' + encodeURIComponent(name)
}
const bundledNames = new Set(bundledLabelFonts.map((f) => f.name))
export const labelFonts: LabelFont[] = [
  ...bundledLabelFonts,
  ...googleFontCatalog
    .filter(([name]) => !bundledNames.has(name))
    .map(([name, category, variants]): LabelFont => {
      const regular = variants
        .filter((v) => !v.endsWith('i'))
        .map(Number)
        .sort((a, b) => Math.abs(a - 400) - Math.abs(b - 400))[0]
      const googleStyle = regular === undefined ? variants[0] : String(regular)
      const weights = [regular ?? parseInt(googleStyle)]
      if (variants.includes('700') && !weights.includes(700)) weights.push(700)
      const cat: Record<string, string> = {
        'Sans Serif': 'Sans serif',
        Handwriting: 'Script & handwritten',
        Monospace: 'Typewriter',
      }
      return {
        name,
        category: cat[category] || category,
        file: googleFontKey(name),
        weights,
        googleStyle,
        smallPrint: false,
        minimumPt: 12,
        license: 'Google Fonts open-source license',
        embedding: true,
        styles: variants.some((v) => v.endsWith('i'))
          ? ['normal', 'italic']
          : ['normal'],
        suitable_for: ['headings'],
        tags: [
          cat[category] || category,
          ...(['Display', 'Handwriting'].includes(category)
            ? ['Seasonal']
            : []),
          ...(category === 'Sans Serif' ? ['Minimal'] : []),
        ],
        readability: 'Review for small print',
        style: category,
        licensedStatus:
          'Open-source family published by Google Fonts; original license available in its Google Fonts listing.',
        source: 'google',
      }
    }),
]
export function fontFileUrl(key: string) {
  if (key.startsWith('custom-'))
    return '/api/workspace?font=' + encodeURIComponent(key.slice(7))
  return key.startsWith('google-')
    ? '/.netlify/functions/google-label-font?font=' + encodeURIComponent(key)
    : '/label-fonts/' + key + '.ttf'
}
export function fontFaceKey(font: LabelFont, bold = false) {
  return font.file + (bold && font.weights.includes(700) ? '-bold' : '')
}
export function resolveFontFace(key: string) {
  return labelFonts.find(
    (f) =>
      f.file === key || (f.weights.includes(700) && f.file + '-bold' === key),
  )
}

export function workspaceFonts(
  records: Record<string, any>[] = [],
): LabelFont[] {
  return records.flatMap((r) => (r.font?.source === 'custom' ? [r.font] : []))
}
